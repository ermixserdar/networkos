const text={en,tr} as const;

export function useTranslation(){
 const language=useAppStore(s=>s.language);
 // Stable per language: screens list `t` in hook deps, and a fresh function every render made
 // focus-refresh effects re-run endlessly (the contacts import screen reloaded in a loop).
 const t=useMemo(()=>translate(language),[language]);
 return {language,t};
}

/** Usable outside React (services, notification bodies). */
export function translate(language:Language){
 return (key:TranslationKey,...args:(string|number)[])=>{
  const table=text[language] as Record<string,Value>;
  const value=table[key]??(en as Record<string,Value>)[key];
  if(value===undefined)return key;
  return typeof value==='function'?value(...args):value;
 };
}

export async function saveLanguage(language:Language){await AsyncStorage.setItem('networkos.language',language);useAppStore.getState().setLanguage(language);}
export function systemLanguage():Language{try{const locale=Intl.DateTimeFormat().resolvedOptions().locale?.toLowerCase()??'en';return locale.startsWith('tr')?'tr':'en';}catch{return 'en';}}
export async function loadLanguage(){const language=await AsyncStorage.getItem('networkos.language');if(language==='en'||language==='tr'){useAppStore.getState().setLanguage(language);return;}useAppStore.getState().setLanguage(systemLanguage());}
export async function saveThemeMode(mode:'system'|'light'|'dark'){await AsyncStorage.setItem('networkos.theme',mode);useAppStore.getState().setThemeMode(mode);}
export async function loadThemeMode(){const mode=await AsyncStorage.getItem('networkos.theme');if(mode==='system'||mode==='light'||mode==='dark')useAppStore.getState().setThemeMode(mode);}
